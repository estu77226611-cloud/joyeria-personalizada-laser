export const PRODUCTOS_VISIBLES = PRODUCTOS.filter((producto) => !producto.oculto);

export function productoPorId(id) {
  return PRODUCTOS.find((producto) => producto.id === Number(id)) || null;
}

export function tipoPorId(id) {
  return TIPOS.find((tipo) => tipo.id === id) || TIPOS[0];
}

export function filtrarPorTipo(tipo) {
  if (!tipo || tipo === 'todos') return PRODUCTOS_VISIBLES;
  return PRODUCTOS_VISIBLES.filter((producto) => producto.tipo === tipo);
}

export function productosDestacados() {
  return PRODUCTOS_VISIBLES.filter((producto) => producto.destacado).slice(0, 6);
}

export function productoParaTipo(tipo) {
  return PRODUCTOS_VISIBLES.find((producto) => producto.tipo === tipo) || PRODUCTOS_VISIBLES[0];
}
